package clientsetup

import (
	"encoding/json"
	"strconv"
	"strings"
)

type Client string

const (
	CodexCLI         Client = "codex_cli"
	CodexDesktop     Client = "codex_desktop"
	ClaudeCode       Client = "claude_code"
	ClaudeConnectors Client = "claude_connectors"
	Composio         Client = "composio"
)

type Mode string

const (
	Local  Mode = "local"
	Remote Mode = "remote"
)

type Auth string

const (
	Bearer Auth = "bearer"
	OAuth  Auth = "oauth"
)

type SupportStatus string

const (
	NotYetVerified SupportStatus = "not_yet_verified"
	Unsupported    SupportStatus = "unsupported"
)

// SetupConfig contains server-owned paths, credential identities and capability
// decisions. Creating/validating the native v2 0600 credential file and private
// Unix-socket handoff belongs to the MCP owner; Render references only the file
// path generated by the application. LocalCredentialID must
// identify that persisted grant, never an in-memory or wildcard owner identity.
type SetupConfig struct {
	ExecutablePath    string `json:"executable_path,omitempty"`
	LocalConfigPath   string `json:"local_config_path,omitempty"`
	LocalCredentialID string `json:"local_credential_id,omitempty"`
	RemoteURL         string `json:"remote_url,omitempty"`
	Auth              Auth   `json:"auth,omitempty"`
	BearerTokenEnv    string `json:"bearer_token_env,omitempty"`
	CredentialID      string `json:"credential_id,omitempty"`
	// Token is accepted only to enforce redaction when preparing bearer guides.
	// It is never rendered, serialized, validated as auth, or persisted here.
	Token string `json:"-"`
	// OAuthAvailable means the actual deployed runtime OAuth route passed its
	// compatibility checks. A configured route or signed fixture is insufficient.
	OAuthAvailable bool `json:"oauth_available"`
	// HeaderAuthAvailable is the owner's confirmed account/org beta capability.
	HeaderAuthAvailable bool `json:"header_auth_available"`
	// If both public modes exist, these must name distinct public hostnames.
	BearerURL string `json:"bearer_url,omitempty"`
	OAuthURL  string `json:"oauth_url,omitempty"`
}

// Diagnostics intentionally omit even noncredential fields: callers can receive
// tainted paths/URLs before validation, and those may themselves contain secrets.
func (SetupConfig) String() string   { return "clientsetup.SetupConfig{credentials:redacted}" }
func (SetupConfig) GoString() string { return "clientsetup.SetupConfig{credentials:redacted}" }

// MarshalJSON keeps diagnostic serialization safe even before validation.
func (cfg SetupConfig) MarshalJSON() ([]byte, error) {
	type plain SetupConfig
	// URLs can contain independent userinfo/query secrets before validation.
	// Diagnostic serialization omits them even when Token is absent/different.
	cfg.RemoteURL, cfg.BearerURL, cfg.OAuthURL = "", "", ""
	if cfg.Token != "" {
		fields := []*string{&cfg.ExecutablePath, &cfg.LocalConfigPath, &cfg.LocalCredentialID, &cfg.RemoteURL, &cfg.BearerTokenEnv, &cfg.CredentialID, &cfg.BearerURL, &cfg.OAuthURL}
		for _, value := range fields {
			*value = strings.ReplaceAll(*value, cfg.Token, "<REDACTED>")
		}
		cfg.Auth = Auth(strings.ReplaceAll(string(cfg.Auth), cfg.Token, "<REDACTED>"))
	}
	cfg.Token = ""
	return json.Marshal(plain(cfg))
}

type Guide struct {
	Client              Client        `json:"client"`
	Mode                Mode          `json:"mode"`
	Status              SupportStatus `json:"status"`
	SupportLabel        string        `json:"support_label"`
	Explanation         string        `json:"explanation"`
	Endpoint            string        `json:"endpoint,omitempty"`
	Configuration       string        `json:"configuration,omitempty"`
	ConfigurationFormat string        `json:"configuration_format,omitempty"`
	Command             string        `json:"command,omitempty"`
	CredentialPlacement string        `json:"credential_placement,omitempty"`
	TestAction          string        `json:"test_action,omitempty"`
	RevokeAction        string        `json:"revoke_action,omitempty"`
	Warnings            []string      `json:"warnings,omitempty"`
	Sources             []string      `json:"sources,omitempty"`
	DocumentationDate   string        `json:"documentation_date"`
	ObservedVersion     string        `json:"observed_version"`
}

// Render produces inert instructions. Documented capability never upgrades an
// exact application/client combination to verified support. No caller-provided
// boolean can change the returned support status to a successful-client claim.
func Render(client Client, mode Mode, cfg SetupConfig) (Guide, error) {
	cfg, err := normalizedConfig(client, mode, cfg)
	if err != nil {
		return Guide{}, err
	}
	guide := baseGuide(client, mode)
	if explanation := unsupportedReason(client, mode, cfg); explanation != "" {
		guide.Status, guide.SupportLabel, guide.Explanation = Unsupported, "Unsupported combination", explanation
		return guide, ErrUnsupported
	}
	guide.Explanation = "This transport is documented. This My WhatsApp MCP connection still needs a successful call from the exact client version."
	if mode == Local {
		return localGuide(guide, cfg), nil
	}
	guide.Endpoint = cfg.RemoteURL
	guide.Warnings = []string{
		"Keep this computer, My WhatsApp MCP and the HTTPS tunnel running while the remote client connects.",
		"Remote results pass through the tunnel provider and the receiving AI service.",
		"Expose only the dedicated MCP listener. Pairing, administration and archive files stay on the separate local interface.",
	}
	if cfg.Auth == OAuth {
		return oauthGuide(guide, cfg), nil
	}
	return bearerGuide(guide, cfg), nil
}

func baseGuide(client Client, mode Mode) Guide {
	g := Guide{Client: client, Mode: mode, Status: NotYetVerified, SupportLabel: "Not yet verified", DocumentationDate: "2026-10-06"}
	switch client {
	case CodexCLI:
		g.ObservedVersion = "Codex CLI 0.149.1"
		g.Sources = []string{"https://learn.chatgpt.com/docs/extend/mcp?surface=cli", "https://developers.openai.com/codex/config-reference"}
	case CodexDesktop:
		g.ObservedVersion = "Codex desktop 26.930.51102 (build 13100), bundled CLI 0.160.0"
		g.Sources = []string{"https://learn.chatgpt.com/docs/extend/mcp?surface=app", "https://developers.openai.com/codex/config-reference"}
	case ClaudeCode:
		g.ObservedVersion = "Claude Code 2.1.291"
		g.Sources = []string{"https://code.claude.com/docs/en/mcp", "https://code.claude.com/docs/en/cli-reference"}
	case ClaudeConnectors:
		g.ObservedVersion = "Claude Desktop 2.19675.1; hosted connector capability is account-dependent"
		g.Sources = []string{"https://claude.com/docs/connectors/custom/add-unlisted", "https://claude.com/docs/connectors/building/authentication"}
	case Composio:
		g.ObservedVersion = "Composio CLI 0.3.1; hosted registration and beta UI not yet verified"
		g.Sources = []string{"https://docs.composio.dev/docs/extending-sessions/custom-mcp", "https://docs.composio.dev/reference/api-reference/toolkits/postCustomToolkitsUpsert"}
	}
	return g
}

func unsupportedReason(client Client, mode Mode, cfg SetupConfig) string {
	if mode == Local {
		switch client {
		case ClaudeConnectors:
			return "Claude web/Desktop remote connectors connect from Anthropic's cloud and cannot reach localhost or start a local stdio adapter. A local Claude Desktop extension is a separate connection mechanism."
		case Composio:
			return "Composio Custom MCP requires a public HTTPS MCP URL; local and stdio-only servers are not supported by this registration route."
		}
		if client == ClaudeCode && (strings.Contains(cfg.ExecutablePath, "${") || strings.Contains(cfg.LocalConfigPath, "${")) {
			return "Claude Code expands ${...} in command and arguments. Documented JSON quoting cannot preserve this literal path; choose executable and credential-file paths without ${ markers."
		}
		return ""
	}
	if cfg.Auth == OAuth {
		if client == Composio {
			return "This Composio guide verifies only the documented API_KEY header mapping. Custom MCP OAuth registration has not been verified for this product route."
		}
		if !cfg.OAuthAvailable {
			return "The actual runtime OAuth route has not passed discovery, registration, PKCE, callback, refresh and identity/policy checks. Configure and verify that route before connecting this client through OAuth."
		}
	}
	if client == ClaudeConnectors && cfg.Auth == Bearer && !cfg.HeaderAuthAvailable {
		return "Claude request-header authentication is a beta for eligible organizations. This account's capability is not confirmed; use an actually verified OAuth route or confirm Request headers is available."
	}
	return ""
}

func localGuide(g Guide, cfg SetupConfig) Guide {
	args := []string{"mcp", "stdio", "--config", cfg.LocalConfigPath}
	g.Command = shellQuote(cfg.ExecutablePath) + " mcp stdio --config " + shellQuote(cfg.LocalConfigPath)
	if g.Client == ClaudeCode {
		g.ConfigurationFormat = "json"
		g.Configuration = jsonConfig(map[string]any{"mcpServers": map[string]any{"wa_indexer": map[string]any{"type": "stdio", "command": cfg.ExecutablePath, "args": args}}})
	} else {
		g.ConfigurationFormat = "toml"
		g.Configuration = "[mcp_servers.wa_indexer]\ncommand = " + tomlString(cfg.ExecutablePath) + "\nargs = [\"mcp\", \"stdio\", \"--config\", " + tomlString(cfg.LocalConfigPath) + "]\n"
	}
	g.CredentialPlacement = "Copy the generated client configuration. My WhatsApp MCP creates the private 0600 credential file in its 0700 directory and connects the adapter through a private Unix socket. You do not need to choose a port, copy the file contents or set a token environment variable. The client receives only the generated file path; secret values stay out of settings, arguments and previews."
	g.TestAction = testTools(g.Client)
	g.RevokeAction = revokeCredential(cfg.LocalCredentialID) + " Then remove this isolated client's wa_indexer registration; deleting its config file alone does not revoke access."
	if g.Client == CodexDesktop {
		g.Warnings = []string{"Verify the desktop app itself. A successful bundled CLI/backend test does not prove desktop configuration loading or a desktop query."}
	}
	return g
}

func bearerGuide(g Guide, cfg SetupConfig) Guide {
	g.CredentialPlacement = "Keep the raw per-client token in the dedicated " + cfg.BearerTokenEnv + " environment variable of this client's process. Do not use an OpenAI, Claude or cloud-account credential. The preview contains no token."
	g.RevokeAction = revokeCredential(cfg.CredentialID) + " Keep the old credential configured for one denied test, then disconnect/remove this client registration."
	g.TestAction = testTools(g.Client)
	switch g.Client {
	case CodexCLI, CodexDesktop:
		g.ConfigurationFormat = "toml"
		g.Configuration = "[mcp_servers.wa_indexer]\nurl = " + tomlString(cfg.RemoteURL) + "\nbearer_token_env_var = " + tomlString(cfg.BearerTokenEnv) + "\n"
		if g.Client == CodexCLI {
			g.Command = "codex mcp add wa_indexer --url " + shellQuote(cfg.RemoteURL) + " --bearer-token-env-var " + shellQuote(cfg.BearerTokenEnv)
		} else {
			g.Warnings = append(g.Warnings, "The desktop process must inherit the dedicated token variable. Setting it in an unrelated terminal does not prove desktop access.")
		}
	case ClaudeCode:
		g.ConfigurationFormat = "json"
		g.Configuration = jsonConfig(map[string]any{"mcpServers": map[string]any{"wa_indexer": map[string]any{"type": "http", "url": cfg.RemoteURL, "headers": map[string]string{"Authorization": "Bearer ${" + cfg.BearerTokenEnv + "}"}}}})
		g.Command = "claude --mcp-config './wa-indexer.mcp.json' --strict-mcp-config"
	case ClaudeConnectors:
		g.ConfigurationFormat = "connector"
		g.Configuration = "Remote MCP URL: " + cfg.RemoteURL + "\nAuthentication: No sign-in\nRequest header: Authorization\nHeader value: Bearer <REDACTED>\nRequired: Yes\n"
		g.CredentialPlacement = "This account must have the request-header beta. Enter the full value Bearer followed by a space and the raw per-client token in Request headers. Claude sends the value literally; this preview is redacted. Do not combine an Authorization request header with OAuth."
		g.Warnings = append(g.Warnings, "A shared organization header credential grants its scoped access to everyone using it; it does not identify an individual member.")
	case Composio:
		g.ConfigurationFormat = "json"
		g.Configuration = jsonConfig(map[string]any{"mode": "API_KEY", "headers": map[string]string{"Authorization": "Bearer {{generic_api_key}}"}})
		g.CredentialPlacement = "Register the API_KEY auth scheme with this explicit Authorization template. Enter the raw My WhatsApp MCP token as the connected account's generic_api_key. The Composio project x-api-key is separate and must not be sent to My WhatsApp MCP."
		g.TestAction = "After authorized registration at the endpoint above, create an active API-key connection and wait for authenticated tool sync. Execute search_messages, get_context, list_chats and get_index_status against a synthetic permitted source. Confirm the actual outgoing header uses Authorization: Bearer, then verify excluded scope and a revoked token are denied."
		g.Warnings = append(g.Warnings, "An API Key dropdown or active connection alone does not prove the outgoing header or successful remote authentication. The experimental registration API and beta dashboard flow may differ.")
	}
	return g
}

func oauthGuide(g Guide, cfg SetupConfig) Guide {
	if g.Client == ClaudeConnectors {
		g.ConfigurationFormat = "connector"
		g.Configuration = "Remote MCP URL: " + cfg.RemoteURL + "\nAuthentication: Sign in now\nOAuth client: the registration method verified for this authorization server\n"
	} else if g.Client == ClaudeCode {
		g.ConfigurationFormat = "json"
		g.Configuration = jsonConfig(map[string]any{"mcpServers": map[string]any{"wa_indexer": map[string]any{"type": "http", "url": cfg.RemoteURL}}})
		g.Command = "claude --mcp-config './wa-indexer.mcp.json' --strict-mcp-config"
	} else {
		g.ConfigurationFormat = "toml"
		g.Configuration = "[mcp_servers.wa_indexer]\nurl = " + tomlString(cfg.RemoteURL) + "\n"
		if g.Client == CodexCLI {
			g.Command = "codex mcp add wa_indexer --url " + shellQuote(cfg.RemoteURL)
		}
	}
	g.CredentialPlacement = "Use the verified authorization server's consent flow. Do not enter a static bearer token or reuse the bearer-only hostname. Client registration and callback URLs must match this exact client surface."
	g.TestAction = "Complete the actual OAuth consent/callback and refresh flow with the intended client, then " + testTools(g.Client)
	g.RevokeAction = "Revoke this connection's access and refresh credentials at the authorization server and remove its My WhatsApp MCP policy grant. Repeat all four tools and refresh with the old connection; both must be denied. Then disconnect the client."
	if cfg.CredentialID != "" {
		g.RevokeAction += " The mapped My WhatsApp MCP credential is " + cfg.CredentialID + "."
	}
	g.Warnings = append(g.Warnings, "An email identity alone does not establish per-client isolation. Distinct OAuth clients require a verifiable client identity or separate configured endpoints/applications.")
	return g
}

func testTools(client Client) string {
	name := string(client)
	return "In a new isolated " + name + " connection, list the four read-only tools and call search_messages on a synthetic permitted phrase. Use its returned message ID for get_context, then call list_chats and get_index_status. Confirm excluded chats/dates are absent, narrow the grant and repeat with the prior message ID; deny out-of-scope results."
}

func revokeCredential(id string) string {
	return "In My WhatsApp MCP's Connect an AI App, revoke credential " + id + ". Repeat search_messages, get_context, list_chats and get_index_status using the old connection; every call must be denied."
}

func shellQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'" }
func tomlString(value string) string { return strconv.Quote(value) }

func jsonConfig(value any) string {
	// Render validates all strings; these maps contain only strings/slices/maps,
	// so encoding/json has no unsupported value or cyclic graph to reject.
	data, _ := json.MarshalIndent(value, "", "  ")
	return string(data) + "\n"
}
